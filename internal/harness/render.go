var ErrConflict = errors.New("HARNESS_CONFLICT: preserve existing or modified integration before retrying")
var ErrPackage = errors.New("HARNESS_PACKAGE: invalid portable entrypoint or metadata")

const header = "<!-- Generated by AIKIT; managed project integration. -->\n"
const begin = "# BEGIN AIKIT MANAGED MCP\n"
const end = "# END AIKIT MANAGED MCP\n"
const researchName = "aikit-repository-research"
const researchSkillName = "aikit-research"

// Portable harness names allow lowercase letters, digits and hyphens, max 64.
// A digest preserves identity when a package ID needs normalization or truncation.
func portableName(id string) string {
	base := strings.NewReplacer(".", "-", "_", "-").Replace(id)
	if base == id && len("aikit-"+base) <= 64 {
		return "aikit-" + base
	}
	if len(base) > 47 {
		base = base[:47]
	}
	h := sha256.Sum256([]byte(id))
	return fmt.Sprintf("aikit-%s-%x", base, h[:5])
}

func entrypoint(p packages.Exported) (name, description, body string, err error) {
	data := p.Files["AGENT.md"]
	if p.Entry.Type == "skill" {
		data = p.Files["SKILL.md"]
	}
	if len(data) == 0 || !utf8.Valid(data) || bytes.IndexByte(data, 0) >= 0 || security.SensitiveContent(data) {
		err = ErrPackage
		return
	}
	body = string(data)
	name = portableName(p.Entry.ID)
	description = "AIKIT installed agent " + p.Entry.ID
	if p.Entry.Type == "agent" {
		if strings.TrimSpace(body) == "" {
			err = ErrPackage
		}
		return
	}
	normalized := strings.ReplaceAll(body, "\r\n", "\n")
	if !strings.HasPrefix(normalized, "---\n") {
		err = ErrPackage
		return
	}
	front, rest, ok := strings.Cut(normalized[4:], "\n---\n")
	if !ok || len(front) > 8192 || strings.TrimSpace(rest) == "" {
		err = ErrPackage
		return
	}
	var meta map[string]any
	decoder := yaml.NewDecoder(strings.NewReader(front))
	if decoder.Decode(&meta) != nil {
		err = ErrPackage
		return
	}
	var extra any
	if decoder.Decode(&extra) != io.EOF {
		err = ErrPackage
		return
	}
	original, ok := meta["name"].(string)
	if !ok || original != p.Entry.ID {
		err = ErrPackage
		return
	}
	description, ok = meta["description"].(string)
	if !ok || strings.TrimSpace(description) == "" || len(description) > 1024 || strings.ContainsAny(description, "\x00\r\n") {
		err = ErrPackage
		return
	}
	// Prevent packages from silently enabling hooks, subagents, or inline MCP.
	// The portable subset is deliberately instruction-only; supporting files remain available.
	if len(meta) != 2 {
		err = ErrPackage
		return
	}
	meta["name"] = name
	encoded, e := yaml.Marshal(meta)
	if e != nil {
		err = ErrPackage
		return
	}
	body = "---\n" + string(encoded) + "---\n" + header + rest
	return
}

func renderPackages(h string, all []packages.Exported) (map[string][]byte, error) {
	files := map[string][]byte{}
	seen := map[string]bool{}
	for _, p := range all {
		name, description, body, err := entrypoint(p)
		if err != nil {
			return nil, err
		}
		identity := p.Entry.Type + ":" + name
		if seen[identity] {
			return nil, ErrConflict
		}
		seen[identity] = true
		if p.Entry.Type == "agent" {
			if h == "claude" {
				front, _ := yaml.Marshal(map[string]string{"name": name, "description": description})
				files[".claude/agents/"+name+".md"] = []byte("---\n" + string(front) + "---\n" + header + body)
			} else {
				data, err := toml.Marshal(map[string]string{"name": name, "description": description, "developer_instructions": strings.TrimSpace(header + body)})
				if err != nil {
					return nil, ErrPackage
				}
				files[".codex/agents/"+name+".toml"] = append([]byte("# Generated by AIKIT; managed project integration.\n"), data...)
			}
			continue
		}
		base := ".agents/skills/" + name + "/"
		if h == "claude" {
			base = ".claude/skills/" + name + "/"
		}
		for path, data := range p.Files {
			folded := strings.ToLower(path)
			if security.HardDenied(path, false) || folded == ".aikit" || strings.HasPrefix(folded, ".aikit/") || strings.HasPrefix(folded, ".claude-plugin/") || strings.HasPrefix(folded, ".codex-plugin/") || folded == "agents/openai.yaml" || security.SensitiveContent(data) {
				return nil, ErrPackage
			}
			if path == "SKILL.md" {
				data = []byte(body)
			}
			files[base+path] = data
		}
	}
	for _, data := range files {
		if len(data) > packages.MaxFileBytes {
			return nil, ErrPackage
		}
	}
	return files, nil
}

func addResearchSkill(base string, files map[string][]byte) error {
	dir := base + "/skills/" + researchSkillName
	entry, workflow := dir+"/SKILL.md", dir+"/workflow.md"
	if _, exists := files[entry]; exists {
		return ErrConflict
	}
	if _, exists := files[workflow]; exists {
		return ErrConflict
	}
	files[entry] = []byte(`---
name: aikit-research
description: Run ConMesh research. Delegate project architecture and team-practice research to a local subagent that updates the AIKIT knowledge manifest.
---
` + header + `# Run ConMesh research

When the user asks to run ConMesh research, delegate from this conversation to
one local subagent that can use the project's AIKIT MCP tools, run AIKIT CLI
commands, and write knowledge proposals in the current project. Use the
` + researchName + ` custom subagent if your host offers it. Otherwise use a
local general-purpose subagent with those capabilities. Use foreground
delegation when needed for normal permission prompts.

Tell the worker to read ` + workflow + ` from the project root and execute that
workflow directly, without delegating it again. Wait for the worker's report
and return the validated proposal IDs and review digests or any blockers.
If your host cannot delegate locally, tell the user instead of claiming a
subagent ran. Keep this conversation and its current project.
`)
	files[workflow] = []byte(strings.ReplaceAll(knowledge.ResearchSkill, "\r\n", "\n"))
	return nil
}

func addResearchAgent(h string, files map[string][]byte) error {
	const description = "Research the local project and prepare evidence-backed knowledge proposals for review."
	workflow := ".agents/skills/" + researchSkillName + "/workflow.md"
	agentPath := ".codex/agents/" + researchName + ".toml"
	if h == "claude" {
		workflow = ".claude/skills/" + researchSkillName + "/workflow.md"
		agentPath = ".claude/agents/" + researchName + ".md"
	}
	if _, exists := files[agentPath]; exists {
		return ErrConflict
	}
	instructions := "Read `" + workflow + "` from the project root and execute the ConMesh research workflow directly. Report validated proposals for human review."
	if h == "claude" {
		meta, err := yaml.Marshal(map[string]string{"name": researchName, "description": description})
		if err != nil {
			return ErrPackage
		}
		files[agentPath] = []byte("---\n" + string(meta) + "---\n" + header + instructions + "\n")
		return nil
	}
	data, err := toml.Marshal(map[string]string{"name": researchName, "description": description, "developer_instructions": instructions})
	if err != nil {
		return ErrPackage
	}
	files[agentPath] = append([]byte("# Generated by AIKIT; managed project integration.\n"), data...)
	return nil
}

func mcpEntry(project, executable string) map[string]any {
	return map[string]any{"command": executable, "args": []string{"mcp", "serve", "--project", project}}
}

// jsonObject rejects duplicate keys at every depth instead of silently discarding
// a user's settings during a map round trip.
func jsonObject(data []byte) (map[string]json.RawMessage, error) {
	if len(data) == 0 {
		return map[string]json.RawMessage{}, nil
	}
	d := json.NewDecoder(bytes.NewReader(data))
	var walk func() error
	walk = func() error {
		token, err := d.Token()
		if err != nil {
			return err
		}
		delim, ok := token.(json.Delim)
		if !ok {
			return nil
		}
		if delim == '{' {
			seen := map[string]bool{}
			for d.More() {
				key, err := d.Token()
				if err != nil {
					return err
				}
				s, ok := key.(string)
				if !ok || seen[s] {
					return ErrConflict
				}
				seen[s] = true
				if err := walk(); err != nil {
					return err
				}
			}
		} else if delim == '[' {
			for d.More() {
				if err := walk(); err != nil {
					return err
				}
			}
		} else {
			return ErrConflict
		}
		_, err = d.Token()
		return err
	}
	if walk() != nil {
		return nil, ErrConflict
	}
	if _, err := d.Token(); err != io.EOF {
		return nil, ErrConflict
	}
	var value map[string]json.RawMessage
	if json.Unmarshal(data, &value) != nil || value == nil {
		return nil, ErrConflict
	}
	return value, nil
}
